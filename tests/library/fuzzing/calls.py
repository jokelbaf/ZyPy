import collections.abc
import os
import typing

import hypothesis
import hypothesis.strategies

EXAMPLES: typing.Final = int(os.environ.get("ZYPY_FUZZ_EXAMPLES", "20"))

SETTINGS: typing.Final = hypothesis.settings(
    max_examples=EXAMPLES,
    deadline=None,
    database=None,
    suppress_health_check=list(hypothesis.HealthCheck),
)


class Arguments(typing.NamedTuple):
    """Positional and keyword arguments for one call."""

    positional: list[object]
    keywords: dict[str, object]

    def apply(self, function: object) -> object:
        """Call `function` with these arguments, returning None on a Python exception."""
        return attempt(function, *self.positional, **self.keywords)


def attempt(function: object, /, *args: object, **kwargs: object) -> object:
    """Call `function` and return None if it raises a Python exception."""
    try:
        return typing.cast("collections.abc.Callable[..., object]", function)(*args, **kwargs)
    except Exception:
        return None


def fuzz[T](strategy: hypothesis.strategies.SearchStrategy[T], check: collections.abc.Callable[[T], object]) -> None:
    """Run `check` on values generated by `strategy`."""

    @SETTINGS
    @hypothesis.given(strategy)
    def run(example: T) -> None:
        """Check one example."""
        check(example)

    run()
